#!/usr/bin/env python3
"""Writes Sources/SortlyCore/Time/CountryTimeZoneTable.swift: each country's time zones with the
places they stand for, for photos whose place is known only offline (review P1-15).

Source: the IANA time zone database (public domain), zone.tab: one principal place per zone and
country. tools/country_time_zones_extra.txt adds more reference places to zones a country already
has, territories the offline map counts as part of a country, and a few codes and disputed areas,
and leaves out the zones of a few enclaves whose clock is that of the country's main zone.

Usage (from the repository root):
    python3 -I tools/gen_country_time_zones.py [<zoneinfo directory>]
The directory defaults to /usr/share/zoneinfo (Debian/Ubuntu package "tzdata"); its tzdata.zi
names the database version written into the table.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTRA = os.path.join(ROOT, "tools", "country_time_zones_extra.txt")
OUT = os.path.join(ROOT, "Sources", "SortlyCore", "Time", "CountryTimeZoneTable.swift")


def coordinate(text):
    """zone.tab's ISO 6709 "+DDMM+DDDMM" or "+DDMMSS+DDDMMSS" in decimal degrees."""
    m = re.fullmatch(r"([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?", text)
    if not m:
        raise SystemExit(f"bad coordinate {text!r}")

    def part(sign, degrees, minutes, seconds):
        value = int(degrees) + int(minutes) / 60 + int(seconds or 0) / 3600
        return -value if sign == "-" else value

    return part(*m.group(1, 2, 3, 4)), part(*m.group(5, 6, 7, 8))


def read_zone_tab(directory):
    zones = {}
    with open(os.path.join(directory, "zone.tab"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            fields = line.rstrip("\n").split("\t")
            latitude, longitude = coordinate(fields[1])
            zones.setdefault(fields[0], []).append((fields[2], latitude, longitude, fields[2]))
    return zones


def database_version(directory):
    with open(os.path.join(directory, "tzdata.zi"), encoding="utf-8") as f:
        first = f.readline()
    m = re.fullmatch(r"# version (\S+)\s*", first)
    if not m:
        raise SystemExit("tzdata.zi does not name its version")
    return m.group(1)


def main():
    directory = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    tab = read_zone_tab(directory)
    table = {code: list(rows) for code, rows in tab.items()}
    areas = {}
    with open(EXTRA, encoding="utf-8") as f:
        lines = [line.split("#", 1)[0].split() for line in f]
    # Merges first: a reference place may name a zone of a merged territory.
    for words in lines:
        if words and words[0] == "MERGE":
            for territory in words[2:]:
                if territory not in tab:
                    raise SystemExit(f"MERGE: {territory} is not in zone.tab")
                table.setdefault(words[1], []).extend(tab[territory])
    # Then the zones left out, before any reference place could name them.
    for words in lines:
        if words and words[0] == "DROP":
            code, zone = words[1], words[2]
            rows = [row for row in table.get(code, []) if row[0] != zone]
            if len(rows) == len(table.get(code, [])) or not rows:
                raise SystemExit(f"DROP: {zone} is not one of several zones of {code}")
            table[code] = rows
    for words in lines:
        if not words or words[0] in ("MERGE", "DROP"):
            continue
        kind = words[0]
        if kind == "ALIAS":
            code, zone = words[1], words[2]
            if code in tab:
                raise SystemExit(f"ALIAS: {code} is in zone.tab already")
            if not any(zone == row[0] for rows in tab.values() for row in rows):
                raise SystemExit(f"ALIAS: {zone} is not in zone.tab")
            table[code] = [(zone, None, None, zone)]
        elif kind == "AREA":
            areas[words[1]] = words[2]
        elif kind == "CITY":
            code, zone, latitude, longitude, name = words[1], words[2], float(words[3]), float(words[4]), " ".join(words[5:])
            if zone not in {row[0] for row in table.get(code, [])}:
                raise SystemExit(f"CITY {name}: {zone} is not a zone of {code}")
            if not (-90 <= latitude <= 90 and -180 <= longitude <= 180):
                raise SystemExit(f"CITY {name}: no such coordinate")
            table[code].append((zone, latitude, longitude, name))
        else:
            raise SystemExit(f"unknown line kind {kind!r}")
    for area, code in areas.items():
        if code not in table:
            raise SystemExit(f"AREA {area}: no zones for {code}")

    version = database_version(directory)
    out = [
        "// Generated by tools/gen_country_time_zones.py from the IANA time zone database",
        f"// (tzdata {version}, zone.tab) and tools/country_time_zones_extra.txt. Do not edit: run the script.",
        "",
        "extension CountryTimeZones {",
        "    /// The version of the time zone database the table was made from.",
        f'    static let databaseVersion = "{version}"',
        "",
        "    /// Each country's time zones, with the places they stand for (latitude, longitude). A",
        "    /// country with one zone has no place: every photo there is in that zone.",
        "    static let table: [String: [Reference]] = [",
    ]
    for code in sorted(table):
        rows = table[code]
        if len({row[0] for row in rows}) == 1:
            out.append(f'        "{code}": [Reference("{rows[0][0]}")],')
            continue
        out.append(f'        "{code}": [')
        for zone, latitude, longitude, name in rows:
            comment = "" if name == zone else f"  // {name}"
            out.append(f'            Reference("{zone}", {latitude:.4f}, {longitude:.4f}),{comment}')
        out.append("        ],")
    out.append("    ]")
    out.append("")
    out.append("    /// Disputed areas (`DisputedAreas`, no country code) whose clock is that of a country's zones.")
    out.append("    static let areas: [String: String] = [")
    for area in sorted(areas):
        out.append(f'        "{area}": "{areas[area]}",')
    out.append("    ]")
    out.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    zones = {row[0] for rows in table.values() for row in rows}
    print(f"{OUT}: tzdata {version}, {len(table)} countries, {len(zones)} zones, "
          f"{sum(len(rows) for rows in table.values() if len({r[0] for r in rows}) > 1)} reference places")


if __name__ == "__main__":
    main()
